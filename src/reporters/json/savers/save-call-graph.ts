// packages/ast-analyzer/src/reporters/json/savers/save-call-graph.ts

import fs from 'fs';
import path from 'path';
import { safeTraverseAST } from '../../modules/utils.js';

// ============================================================
// СОХРАНЕНИЕ РЕЗУЛЬТАТА АНАЛИЗА ГРАФА ВЫЗОВОВ
// ============================================================

/**
 * Сохраняет результат анализа графа вызовов (CallGraphResult)
 * в JSON-файл на диске.
 *
 * ════════════════════════════════════════════════════════════
 * НАЗНАЧЕНИЕ
 * ════════════════════════════════════════════════════════════
 *
 * Используется в `cli.ts` для сохранения результата работы
 * `buildCallGraphBetweenFunctions` (см. `modes/project-graph.ts`).
 *
 * Результат содержит:
 *   - `from`  — стартовая функция
 *   - `to`    — конечная функция
 *   - `path`  — массив имён функций, образующих путь
 *   - `found` — был ли найден путь
 *   - `nodes` — массив узлов с метаданными (модуль, строка, async)
 *   - `edges` — массив рёбер (from → to, строка)
 *   - `reason` — причина, если путь не найден
 *
 * ════════════════════════════════════════════════════════════
 * БЕЗОПАСНОСТЬ
 * ════════════════════════════════════════════════════════════
 *
 * Функция безопасно обрабатывает:
 *   - циклические ссылки (через `safeTraverseAST`)
 *   - `Map` и `Set` (преобразуются в объекты / массивы)
 *   - опасные ключи (`__proto__`, `constructor`, `_safeInfo`)
 *     — удаляются из результата
 *
 * ════════════════════════════════════════════════════════════
 * АВТОСОЗДАНИЕ ДИРЕКТОРИИ
 * ════════════════════════════════════════════════════════════
 *
 * Если родительская директория для `outputPath` не существует,
 * она создаётся рекурсивно (`fs.mkdirSync` с `recursive: true`).
 * Это защищает от ошибки `ENOENT`, когда cli вызывается в новой
 * рабочей директории.
 *
 * @param callGraphResult — результат работы CallGraph-анализа
 * @param outputPath      — путь к файлу для сохранения
 */
export function saveCallGraphResult(
  callGraphResult: any,
  outputPath: string
): void {
  // ────────────────────────────────────────────────────────
  // Шаг 1: Очистка и подготовка данных
  // ────────────────────────────────────────────────────────
  // safeTraverseAST рекурсивно обходит объект и:
  //   - заменяет циклические ссылки на "[Circular]"
  //   - удаляет ключи _safeInfo, __proto__, constructor, prototype
  //   - обрабатывает Map/Set (если встретятся)
  const safeData = safeTraverseAST(callGraphResult);

  // ────────────────────────────────────────────────────────
  // Шаг 2: Сериализация в JSON
  // ────────────────────────────────────────────────────────
  const json = JSON.stringify(
    safeData,
    (key, value) => {
      // Дополнительная защита: обработка Map и Set
      if (value instanceof Map) {
        return Object.fromEntries(value);
      }
      if (value instanceof Set) {
        return Array.from(value);
      }
      // Удаляем служебные поля
      if (
        key === '_safeInfo' ||
        key === '__proto__' ||
        key === 'constructor'
      ) {
        return undefined;
      }
      return value;
    },
    2
  );

  // ────────────────────────────────────────────────────────
  // Шаг 3: Гарантируем существование директории
  // ────────────────────────────────────────────────────────
  const outputDir = path.dirname(outputPath);
  if (!fs.existsSync(outputDir)) {
    fs.mkdirSync(outputDir, { recursive: true });
  }

  // ────────────────────────────────────────────────────────
  // Шаг 4: Сохранение файла
  // ────────────────────────────────────────────────────────
  fs.writeFileSync(outputPath, json, 'utf-8');
}

// ============================================================
// ЭКСПОРТ ПО УМОЛЧАНИЮ
// ============================================================

export default saveCallGraphResult;