/**
 * Пороги для классификации "тяжёлых" значений.
 *
 * ════════════════════════════════════════════════════════════
 * СЕМАНТИКА
 * ════════════════════════════════════════════════════════════
 *
 *   ┌───────────────────────┬───────────────┬──────────────────────┐
 *   │ Поле                  │ Порог         │ Что классифицируется │
 *   ├───────────────────────┼───────────────┼──────────────────────┤
 *   │ STRING_LENGTH         │ 200           │ Строки → 'template'  │
 *   │ ARRAY_LENGTH          │ 50            │ Массивы → 'flag-array'│
 *   │ OBJECT_JSON_LENGTH    │ 500           │ Объекты → 'config'   │
 *   └───────────────────────┴───────────────┴──────────────────────┘
 *
 * ════════════════════════════════════════════════════════════
 * ПОЧЕМУ ИМЕННО ЭТИ ЗНАЧЕНИЯ
 * ════════════════════════════════════════════════════════════
 *
 *   STRING_LENGTH = 200:
 *     Строки-связи (имена, ключи, коды) редко превышают 200
 *     символов. HTML/CSS-шаблоны — обычно тысячи символов.
 *
 *   ARRAY_LENGTH = 50:
 *     Массивы-связи (например, [constIdx, valueIdx]) короткие.
 *     Массивы флагов (INTRINSIC_TAGS, BUILTIN_FUNCTIONS)
 *     содержат десятки элементов.
 *
 *   OBJECT_JSON_LENGTH = 500:
 *     Объекты-связи (например, SCHEMAS) редко превышают 500
 *     символов. CompactReportConfig с presets — десятки тысяч.
 *
 * ════════════════════════════════════════════════════════════
 * ГДЕ ИСПОЛЬЗУЕТСЯ
 * ════════════════════════════════════════════════════════════
 *
 *   • values-filter.ts::isValueKept     — фильтрация values[]
 *   • values-filter.ts::classifyValue   — классификация kind
 *   • compact-reporter.ts (через isValueKept) — фильтрация cn.value
 *   • codec-encode.ts::addValue         — защита от добавления
 *                                          отфильтрованных значений
 *   • verify-roundtrip.ts::invariantI14 — проверка согласованности
 *   • verify-consistency.ts             — проверка compact ↔ full
 *
 * ⚠️ НЕ ДУБЛИРУЙТЕ эти константы в других файлах. Если нужно
 *    изменить порог — измените здесь, и это применится везде.
 */
export const VALUE_THRESHOLDS = {
  /**
   * Строки длиннее этого порога классифицируются как
   * 'template' (HTML/CSS/JS-шаблоны) и удаляются в режиме
   * 'relations'.
   *
   * Значение по умолчанию: 200.
   */
  STRING_LENGTH: 200,

  /**
   * Массивы длиннее этого порога классифицируются как
   * 'flag-array' (длинные массивы флагов/чисел) и удаляются.
   *
   * Значение по умолчанию: 50.
   */
  ARRAY_LENGTH: 50,

  /**
   * Объекты, чья stableStringify-сериализация длиннее этого
   * порога, классифицируются как 'config' и удаляются.
   *
   * Значение по умолчанию: 500.
   */
  OBJECT_JSON_LENGTH: 500,
} as const;

/**
 * Тип порогов (для типизации в других модулях).
 *
 * ════════════════════════════════════════════════════════════
 * ИСПОЛЬЗОВАНИЕ
 * ════════════════════════════════════════════════════════════
 *
 *   import type { ValueThresholds } from './thresholds.js';
 *
 *   function myFilter(thresholds: ValueThresholds): void {
 *     console.log(thresholds.STRING_LENGTH);
 *     console.log(thresholds.ARRAY_LENGTH);
 *     console.log(thresholds.OBJECT_JSON_LENGTH);
 *   }
 *
 * ════════════════════════════════════════════════════════════
 * СТРУКТУРА
 * ════════════════════════════════════════════════════════════
 *
 *   {
 *     readonly STRING_LENGTH: 200,
 *     readonly ARRAY_LENGTH: 50,
 *     readonly OBJECT_JSON_LENGTH: 500,
 *   }
 *
 * Благодаря `as const` все поля — readonly с литеральными
 * типами (200, 50, 500), а не `number`.
 */
export type ValueThresholds = typeof VALUE_THRESHOLDS;

// ============================================
// ЭКСПОРТ ПО УМОЛЧАНИЮ
// ============================================

export default VALUE_THRESHOLDS;
