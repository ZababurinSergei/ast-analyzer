// Единый источник истины для порогов, используемых в:
//   • compact-reporter.ts::shouldKeepValue
//   • values-filter.ts::classifyValue
//   • codec-encode.ts::addValue
//
// ════════════════════════════════════════════════════════════
// ПОЧЕМУ ЭТО КРИТИЧНО
// ════════════════════════════════════════════════════════════
//
// Ранее пороги были продублированы в двух файлах:
//   • compact-reporter.ts (HEAVY_VALUE_THRESHOLDS)
//   • values-filter.ts (STRING_TEMPLATE_THRESHOLD, ...)
//
// Если значения порогов РАСХОДЯТСЯ, то одно и то же значение
// может:
//   • пройти shouldKeepValue (попасть в full.constants[].value)
//   • НЕ пройти classifyValue (не попасть в valueDict)
//
// Это приводило к рассинхрону values[] между compact на диске
// и encode(full), и, как следствие, к падению L0/L3/RE.
//
// Симптом в verify-roundtrip.ts:
//   $.values.length          a: 206  b: 208
//   $.cn.nonEmptyV[180][1]   a: 3    b: 54
//
// ════════════════════════════════════════════════════════════
// ЗНАЧЕНИЯ
// ════════════════════════════════════════════════════════════
//
//   STRING_LENGTH:
//     Строки длиннее этого порога классифицируются как
//     'template' (HTML/CSS/JS-шаблоны) и удаляются в режиме
//     'relations'.
//
//   ARRAY_LENGTH:
//     Массивы длиннее этого порога классифицируются как
//     'flag-array' (длинные массивы флагов/чисел) и удаляются.
//
//   OBJECT_JSON_LENGTH:
//     Объекты, чья stableStringify-сериализация длиннее этого
//     порога, классифицируются как 'config' и удаляются.
//
// ⚠️ ВАЖНО: любое изменение значений здесь автоматически
//    применяется во всех трёх местах. НЕ дублируйте эти
//    константы в других файлах.
//
// ════════════════════════════════════════════════════════════
// ПРИМЕРЫ
// ════════════════════════════════════════════════════════════
//
//   // Строка 150 символов — остаётся (150 <= 200)
//   VALUE_THRESHOLDS.STRING_LENGTH;  // → 200
//
//   // Массив из 30 элементов — остаётся (30 <= 50)
//   VALUE_THRESHOLDS.ARRAY_LENGTH;   // → 50
//
//   // Объект с stableStringify-длиной 400 — остаётся (400 <= 500)
//   VALUE_THRESHOLDS.OBJECT_JSON_LENGTH;  // → 500
//
// ════════════════════════════════════════════════════════════
// ИСПОЛЬЗОВАНИЕ
// ════════════════════════════════════════════════════════════
//
//   // В values-filter.ts
//   import { VALUE_THRESHOLDS } from './thresholds.js';
//
//   export function isValueKept(value: unknown, mode: ValuesMode): boolean {
//     if (typeof value === 'string') {
//       return value.length <= VALUE_THRESHOLDS.STRING_LENGTH;
//     }
//     // ...
//   }
//
//   // В compact-reporter.ts
//   import { isValueKept } from './codec/values-filter.js';
//
//   const valueToStore = isValueKept(cn.value, valuesMode)
//     ? cn.value
//     : undefined;
//
// ════════════════════════════════════════════════════════════
// СВЯЗАННЫЕ ФАЙЛЫ
// ════════════════════════════════════════════════════════════
