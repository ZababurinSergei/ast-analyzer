// src/reporters/compact/persistence/save-json.ts
// ============================================================
// СОХРАНЕНИЕ JSON-ФАЙЛОВ С САНИТИЗАЦИЕЙ (v1.0.0)
// ============================================================
// Версия: 1.0.0
//
// НАЗНАЧЕНИЕ
// ----------
// Сохранение любого JSON-объекта на диск с гарантией, что:
//   • директория создана
//   • данные JSON-safe (Set/Map/RegExp/Date/BigInt не потеряются)
//   • возвращаются путь и размер файла
//
// ════════════════════════════════════════════════════════════
// ПОЧЕМУ jsonSafeStringify, А НЕ JSON.stringify
// ════════════════════════════════════════════════════════════
//
//   Нативный JSON.stringify теряет данные для:
//     • Set              → '{}'  (пустой объект)
//     • Map              → '{}'  (пустой объект)
//     • RegExp           → '{}'  (пустой объект)
//     • BigInt           → падает с ошибкой
//     • Circular         → падает с ошибкой
//     • class instances  → '{}'  (если нет toJSON)
//
//   Если такие объекты попадают в compact.json, при записи
//   на диск они превращаются в '{}', и round-trip теряет
//   данные. Симптом в verify-consistency:
//     $.values.length   a: 703  b: 553
//     L0/L1/L2/L3/RE — FAIL
//
//   jsonSafeStringify (из codec/stable-stringify.js v1.0.2)
//   рекурсивно санитизирует:
//     • Set    → массив
//     • Map    → plain object
//     • RegExp → строка '/pattern/flags'
//     • Date   → ISO-строка
//     • BigInt → строка '123n'
//     • Circular → '[Circular]'
//
// ════════════════════════════════════════════════════════════
// АВТОСОЗДАНИЕ ДИРЕКТОРИИ
// ════════════════════════════════════════════════════════════
//
//   Если пользователь передал './dist/reports/index.json',
//   а './dist/reports/' не существует — создаём рекурсивно
//   через fs.mkdirSync(dir, { recursive: true }).
//
// ════════════════════════════════════════════════════════════
// ВОЗВРАЩАЕМЫЙ РЕЗУЛЬТАТ
// ════════════════════════════════════════════════════════════
//
//   { path: '/abs/path/index.json', size: 173_456 }
//
//   Размер (size) вычисляется через fs.statSync ПОСЛЕ записи —
//   это точный размер в байтах на диске (может отличаться от
//   Buffer.byteLength(json, 'utf-8') из-за BOM или других
//   особенностей файловой системы).
// ============================================================

import fs from 'fs';
import path from 'path';
import { jsonSafeStringify } from '../../codec/stable-stringify.js';

// ============================================================
// ТИП РЕЗУЛЬТАТА
// ============================================================

/**
 * Результат сохранения JSON-файла.
 */
export interface SaveJsonResult {
    /** Абсолютный путь к сохранённому файлу */
    path: string;
    /** Размер файла в байтах */
    size: number;
}

// ============================================================
// ОСНОВНАЯ ФУНКЦИЯ
// ============================================================

/**
 * Сохраняет данные в JSON-файл с санитизацией.
 *
 * ════════════════════════════════════════════════════════════
 * АЛГОРИТМ
 * ════════════════════════════════════════════════════════════
 *
 *   1. Получить директорию файла через path.dirname.
 *   2. Если директория не существует — создать рекурсивно.
 *   3. Сериализовать через jsonSafeStringify.
 *   4. Записать в файл (utf-8).
 *   5. Получить размер через fs.statSync.
 *   6. Если verbose — вывести строку лога.
 *   7. Вернуть { path, size }.
 *
 * ════════════════════════════════════════════════════════════
 * ПРИМЕРЫ
 * ════════════════════════════════════════════════════════════
 *
 *   // Обычный вызов
 *   const result = saveJsonFile(
 *     './dist/index.json',
 *     compact,
 *     'Сжатый JSON',
 *     true
 *   );
 *   // → { path: './dist/index.json', size: 173_456 }
 *   // В консоль: '   💾 Сжатый JSON: ./dist/index.json (169.39 KB)'
 *
 *   // Директория не существует
 *   saveJsonFile('./a/b/c/d/index.json', data, 'Report', false);
 *   // → создаст ./a/b/c/d/ рекурсивно
 *
 * ════════════════════════════════════════════════════════════
 * ФОРМАТ ЛОГА
 * ════════════════════════════════════════════════════════════
 *
 *   💾 {label}: {filePath} ({sizeKB} KB)
 *
 *   Пример:
 *     💾 Сжатый JSON: ./dist/index.json (169.39 KB)
 *     💾 Полный JSON: ./dist/index.full.json (1204.56 KB)
 *     💾 Edges JSON (2341 edges): ./dist/index.edges.json (456.78 KB)
 *
 * ════════════════════════════════════════════════════════════
 * ОБРАБОТКА ОШИБОК
 * ════════════════════════════════════════════════════════════
 *
 *   Функция НЕ оборачивает ошибки в try/catch:
 *     • fs.mkdirSync — может бросить EACCES/EPERM
 *     • jsonSafeStringify — может бросить при circular
 *     • fs.writeFileSync — может бросить ENOSPC
 *     • fs.statSync — может бросить ENOENT
 *
 *   Это осознанно: вызывающий код (generateCompactReport)
 *   сам решает, как реагировать. Верхний уровень ловит
 *   ошибку и показывает пользователю.
 *
 * ════════════════════════════════════════════════════════════
 * КОДИРОВКА
 * ════════════════════════════════════════════════════════════
 *
 *   Всегда utf-8, без BOM. Это критично для последующего
 *   чтения через readAndDecode / readFullJson — они тоже
 *   читают как utf-8.
 *
 * ════════════════════════════════════════════════════════════
 * СВЯЗАННЫЕ ФАЙЛЫ
 * ════════════════════════════════════════════════════════════
 *
 *   • orchestration/generate-report.ts — вызывает saveJsonFile
 *   • codec/stable-stringify.ts        — jsonSafeStringify
 *   • orchestration/decode-report.ts   — читает обратно
 * ============================================================
 *
 * @param filePath — путь к файлу (относительный или абсолютный)
 * @param data     — данные для сохранения (любой JSON-совместимый объект)
 * @param label    — название для лога (например, 'Сжатый JSON')
 * @param verbose  — выводить ли лог-строку
 * @returns { path, size }
 */
export function saveJsonFile(
    filePath: string,
    data: unknown,
    label: string,
    verbose: boolean
): SaveJsonResult {
    // 1. Создать директорию, если её нет
    const outputDir = path.dirname(filePath);
    if (!fs.existsSync(outputDir)) {
        fs.mkdirSync(outputDir, { recursive: true });
    }

    // 2. Санитизирующая сериализация
    const json = jsonSafeStringify(data);

    // 3. Запись
    fs.writeFileSync(filePath, json, 'utf-8');

    // 4. Размер на диске
    const size = fs.statSync(filePath).size;

    // 5. Лог
    if (verbose) {
        const sizeKB = (size / 1024).toFixed(2);
        console.log(`   💾 ${label}: ${filePath} (${sizeKB} KB)`);
    }

    return { path: filePath, size };
}

// ============================================================
// ЭКСПОРТ ПО УМОЛЧАНИЮ
// ============================================================

export default saveJsonFile;
