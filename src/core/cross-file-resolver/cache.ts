//
// НАЗНАЧЕНИЕ
// ----------
// Кэширует результаты resolveCallee по ключу callSiteKey.
//
// ════════════════════════════════════════════════════════════
// ЗАЧЕМ НУЖЕН ЭТОТ КЭШ
// ════════════════════════════════════════════════════════════
//
//   1. Один и тот же call site может быть обработан несколько
//      раз — например, при повторных проходах по SourceFile
//      или при параллельном резолвинге.
//
//   2. resolveCallee дорогой — symbol lookup через ts-morph
//      может занимать 1–10 мс на вызов. Кэш экономит время
//      при повторных обращениях.
//
//   3. Отрицательные результаты тоже кэшируются (null) —
//      это предотвращает повторные попытки резолвить
//      заведомо неразрешимые вызовы (например, obj[key]()).
//
// ════════════════════════════════════════════════════════════
// КЛЮЧ
// ════════════════════════════════════════════════════════════
//
//   `${filePath}:${line}:${column}`
//
//   Это уникально идентифицирует место вызова в файле:
//     - filePath — путь к SourceFile (виртуальный для .vue)
//     - line     — номер строки вызова (1-based)
//     - column   — номер колонки вызова (1-based)
//
//   Например:
//     /src/a.ts:15:26
//     /src/App.vue.__script__.ts:3:10
//
// ════════════════════════════════════════════════════════════
// ЖИЗНЕННЫЙ ЦИКЛ
// ════════════════════════════════════════════════════════════
//
//   const cache = new ResolveCache();
//
//   const key = ResolveCache.makeKey(filePath, line, column);
//   let resolved = cache.get(key);
//   if (resolved === undefined) {
//     resolved = resolver.resolveCallee(node);
//     cache.set(key, resolved);
//   }
//
//   // ... в конце ...
//   cache.clear();
//
// ════════════════════════════════════════════════════════════
// ТРИ СОСТОЯНИЯ ВОЗВРАТА get()
// ════════════════════════════════════════════════════════════
//
//   - `undefined` — нет в кэше (нужно резолвить)
//   - `null`      — резолвинг не удался (кэшировано)
//   - `ResolvedCallee` — успешный резолвинг
//
//   Это важно: `undefined` ≠ `null`. Первое означает
//   "не знаю", второе — "знаю, что не резолвится".
//
// ════════════════════════════════════════════════════════════
// ПРОИЗВОДИТЕЛЬНОСТЬ
// ════════════════════════════════════════════════════════════
//
//   - Map<->get/set — O(1).
//   - Память: ~100 байт на запись (ключ + объект или null).
//   - Для 10k call sites: ~1 MB. Приемлемо.
//
// ============================================================

import type { ResolvedCallee } from './types.js';

// ============================================================
// ОСНОВНОЙ КЛАСС
// ============================================================

/**
 * Кэш результатов resolveCallee.
 *
 * ════════════════════════════════════════════════════════════
 * ЧТО КЭШИРУЕТ
 * ════════════════════════════════════════════════════════════
 *
 *   Ключ: `${filePath}:${line}:${column}` — call site.
 *   Значение:
 *     - `ResolvedCallee` — если резолвинг удался
 *     - `null`           — если резолвинг не удался (отрицательный кэш)
 *
 * ════════════════════════════════════════════════════════════
 * ЧЕГО НЕ КЭШИРУЕТ
 * ════════════════════════════════════════════════════════════
 *
 *   - ts-morph Node — они инвалидируются при изменении SourceFile.
 *   - Symbol — по той же причине.
 *   - SourceFile — тяжёлый объект, кэшируется внутри Project.
 *
 *   Кэшируем только примитивы: filePath, line, column, name, kind.
 *
 * ════════════════════════════════════════════════════════════
 * ИНВАЛИДАЦИЯ
 * ════════════════════════════════════════════════════════════
 *
 *   Кэш инвалидируется вручную через `clear()`.
 *   Автоматической инвалидации нет — это by design, потому что
 *   в рамках одного прогона резолвера SourceFile не меняются.
 *
 *   Если SourceFile изменились (например, через
 *   `sourceFile.replaceWithText()`), нужно вызвать `clear()`.
 *
 * ════════════════════════════════════════════════════════════
 * СТАТИСТИКА
 * ════════════════════════════════════════════════════════════
 *
 *   `getStats()` возвращает:
 *     - hits   — попаданий в кэш (get вернул не undefined)
 *     - misses — промахов кэша (get вернул undefined)
 *     - size   — текущий размер кэша (количество ключей)
 *
 *   Используется в `ResolveStats` для отладки производительности.
 */
export class ResolveCache {
  // ==========================================================
  // СВОЙСТВА
  // ==========================================================

  /**
   * Основное хранилище кэша.
   *
   * Ключ: `${filePath}:${line}:${column}`
   * Значение: `ResolvedCallee` или `null`
   *
   * Используем `Map` вместо `Object`, потому что:
   *   - ключи — произвольные строки (могут содержать ':', '/', '\')
   *   - Map не имеет prototype pollution
   *   - Map работает быстрее для частых get/set
   */
  private cache = new Map<string, ResolvedCallee | null>();

  /**
   * Статистика попаданий/промахов.
   *
   * Обновляется в `get()`.
   */
  private stats = {
    hits: 0,
    misses: 0,
  };

  // ==========================================================
  // СТАТИЧЕСКИЕ МЕТОДЫ
  // ==========================================================

  /**
   * Формирует ключ для call site.
   *
   * ════════════════════════════════════════════════════════════
   * ФОРМАТ
   * ════════════════════════════════════════════════════════════
   *
   *   `${filePath}:${line}:${column}`
   *
   * ════════════════════════════════════════════════════════════
   * ПОЧЕМУ СТАТИЧЕСКИЙ
   * ════════════════════════════════════════════════════════════
   *
   *   Формирование ключа не зависит от состояния кэша.
   *   Статический метод позволяет:
   *     - формировать ключ без создания экземпляра
   *     - использовать ключ в других модулях (например, для
   *       отладки или логирования)
   *     - тестировать формат ключа изолированно
   *
   * ════════════════════════════════════════════════════════════
   * ПРИМЕР
   * ════════════════════════════════════════════════════════════
   *
   *   ResolveCache.makeKey('/src/a.ts', 15, 26);
   *   // → '/src/a.ts:15:26'
   *
   *   ResolveCache.makeKey('/src/App.vue.__script__.ts', 3, 10);
   *   // → '/src/App.vue.__script__.ts:3:10'
   *
   * @param filePath — путь к SourceFile (виртуальный для .vue)
   * @param line     — номер строки (1-based)
   * @param column   — номер колонки (1-based)
   * @returns строковый ключ
   */
  static makeKey(filePath: string, line: number, column: number): string {
    return `${filePath}:${line}:${column}`;
  }

  // ==========================================================
  // ПУБЛИЧНЫЙ API
  // ==========================================================

  /**
   * Возвращает результат из кэша.
   *
   * ════════════════════════════════════════════════════════════
   * ТРИ СОСТОЯНИЯ ВОЗВРАТА
   * ════════════════════════════════════════════════════════════
   *
   *   - `undefined` — ключа нет в кэше. Значит, резолвинг
   *     ещё не выполнялся. Нужно вызвать resolver.resolveCallee.
   *
   *   - `null` — резолвинг уже выполнялся и не удался.
   *     Повторные попытки бесполезны (символ неразрешим).
   *
   *   - `ResolvedCallee` — резолвинг удался. Можно использовать.
   *
   * ════════════════════════════════════════════════════════════
   * СТАТИСТИКА
   * ════════════════════════════════════════════════════════════
   *
   *   - Если ключ есть в кэше → `hits++` (включая случай null).
   *   - Если ключа нет → `misses++`.
   *
   *   `null` считается попаданием, потому что это валидный
   *   закэшированный результат (отрицательный).
   *
   * ════════════════════════════════════════════════════════════
   * ПРИМЕР
   * ════════════════════════════════════════════════════════════
   *
   *   const key = ResolveCache.makeKey('/src/a.ts', 15, 26);
   *   const cached = cache.get(key);
   *
   *   if (cached === undefined) {
   *     // Не в кэше — резолвим
   *     const resolved = resolver.resolveCallee(node);
   *     cache.set(key, resolved);
   *   } else {
   *     // В кэше — используем
   *     // cached может быть null или ResolvedCallee
   *   }
   *
   * @param key — ключ, сформированный `makeKey()`
   * @returns `undefined` | `null` | `ResolvedCallee`
   */
  get(key: string): ResolvedCallee | null | undefined {
    if (this.cache.has(key)) {
      this.stats.hits++;
      return this.cache.get(key);
    }
    this.stats.misses++;
    return undefined;
  }

  /**
   * Сохраняет результат в кэш.
   *
   * ════════════════════════════════════════════════════════════
   * ЧТО СОХРАНЯЕТ
   * ════════════════════════════════════════════════════════════
   *
   *   - `ResolvedCallee` — успешный резолвинг.
   *   - `null` — отрицательный результат. Это важно: мы
   *     кэшируем и неудачные попытки, чтобы не повторять их.
   *
   * ════════════════════════════════════════════════════════════
   * ПЕРЕЗАПИСЬ
   * ════════════════════════════════════════════════════════════
   *
   *   Если ключ уже существует — значение перезаписывается.
   *   Это может быть полезно при повторном резолвинге после
   *   изменения SourceFile (но обычно используется `clear()`).
   *
   * ════════════════════════════════════════════════════════════
   * ПРИМЕР
   * ════════════════════════════════════════════════════════════
   *
   *   const key = ResolveCache.makeKey('/src/a.ts', 15, 26);
   *
   *   // Успешный резолвинг
   *   cache.set(key, { filePath: '/src/a.ts', line: 1, column: 1, name: 'foo', kind: 'function' });
   *
   *   // Отрицательный результат
   *   cache.set(key, null);
   *
   * @param key   — ключ, сформированный `makeKey()`
   * @param value — `ResolvedCallee` или `null`
   */
  set(key: string, value: ResolvedCallee | null): void {
    this.cache.set(key, value);
  }

  /**
   * Возвращает статистику кэша.
   *
   * ════════════════════════════════════════════════════════════
   * ПОЛЯ
   * ════════════════════════════════════════════════════════════
   *
   *   - `hits`   — количество попаданий (get вернул не undefined)
   *   - `misses` — количество промахов (get вернул undefined)
   *   - `size`   — текущее количество ключей в кэше
   *
   * ════════════════════════════════════════════════════════════
   * ПРИМЕНЕНИЕ
   * ════════════════════════════════════════════════════════════
   *
   *   const stats = cache.getStats();
   *   const hitRate = stats.hits / (stats.hits + stats.misses);
   *   console.log(`Cache hit rate: ${(hitRate * 100).toFixed(1)}%`);
   *
   *   // В ResolveStats:
   *   stats.cacheHits = cacheStats.hits;
   *   stats.cacheMisses = cacheStats.misses;
   *
   * ════════════════════════════════════════════════════════════
   * ВОЗВРАЩАЕМАЯ КОПИЯ
   * ════════════════════════════════════════════════════════════
   *
   *   Возвращаем **копию** объекта статистики, а не ссылку.
   *   Это защищает от случайного изменения статистики
   *   снаружи.
   *
   * @returns `{ hits, misses, size }`
   */
  getStats(): { hits: number; misses: number; size: number } {
    return {
      hits: this.stats.hits,
      misses: this.stats.misses,
      size: this.cache.size,
    };
  }

  /**
   * Очищает кэш и статистику.
   *
   * ════════════════════════════════════════════════════════════
   * ЧТО ДЕЛАЕТ
   * ════════════════════════════════════════════════════════════
   *
   *   1. Очищает `cache` (удаляет все ключи).
   *   2. Сбрасывает `stats.hits` и `stats.misses` в 0.
   *
   * ════════════════════════════════════════════════════════════
   * КОГДА ИСПОЛЬЗОВАТЬ
   * ════════════════════════════════════════════════════════════
   *
   *   - После изменения SourceFile через `replaceWithText()`.
   *   - В тестах — для изоляции между тестами.
   *   - Если вы хотите замерить чистую производительность
   *     без кэша (для профилирования).
   *   - При завершении резолвера (`dispose()` в
   *     `resolveCrossFileCalls`).
   *
   * ════════════════════════════════════════════════════════════
   * ПРИМЕР
   * ════════════════════════════════════════════════════════════
   *
   *   cache.clear();
   *   cache.getStats();  // → { hits: 0, misses: 0, size: 0 }
   */
  clear(): void {
    this.cache.clear();
    this.stats = { hits: 0, misses: 0 };
  }
}

// ============================================================
// ЭКСПОРТ ПО УМОЛЧАНИЮ
// ============================================================
// Класс ResolveCache уже экспортирован через `export class`.
// Default-экспорт оставлен для совместимости.
// ============================================================

export default ResolveCache;
