//   - Возвращает абсолютные пути
//   - Убирает дубликаты через Set
//   - Работает как с файлами, так и с директориями
//   - Не выбрасывает исключения при отсутствующих путях
//     (только предупреждения в консоль)
//   - ✅ v1.1.0: принимает дополнительные ignore-паттерны
// ============================================

import fs from 'fs';
import path from 'path';
import { glob } from 'glob';

// ============================================
// КОНСТАНТЫ
// ============================================

/**
 * Поддерживаемые расширения файлов.
 *
 * Единый список — не дублируется в других модулях.
 * Если нужно добавить новое расширение (например, `.mts`, `.cts`),
 * достаточно отредактировать этот массив — все потребители
 * автоматически подхватят изменение.
 */
const DEFAULT_EXTENSIONS: readonly string[] = [
  '.ts',
  '.tsx',
  '.js',
  '.jsx',
  '.mjs',
  '.cjs',
  '.vue',
];

/**
 * Паттерны, которые всегда исключаются из анализа.
 *
 * Используются в `glob({ ignore: [...] })`. Паттерны заданы
 * в формате minimatch (совместим с glob).
 *
 * ✅ v1.1.0: к этому списку добавляются `additionalIgnore`,
 * переданные третьим аргументом.
 */
const DEFAULT_IGNORE: readonly string[] = [
  '**/node_modules/**',
  '**/dist/**',
  '**/build/**',
  '**/coverage/**',
  '**/*.d.ts',
];

// ============================================
// ОСНОВНАЯ ФУНКЦИЯ
// ============================================

/**
 * Собирает все файлы для анализа по указанным путям.
 *
 * ════════════════════════════════════════════════════════════
 * ПОВЕДЕНИЕ
 * ════════════════════════════════════════════════════════════
 *
 *   Для каждого пути:
 *     - Если это файл с поддерживаемым расширением —
 *       добавляется в результат.
 *     - Если это директория — рекурсивно (или нет)
 *       собираются все файлы с поддерживаемыми расширениями.
 *     - Если путь не существует — выводится предупреждение
 *       и путь пропускается (без выброса исключения).
 *
 *   На выходе:
 *     - Абсолютные пути (path.resolve)
 *     - Без дубликатов (Set)
 *     - Без node_modules, dist, build, coverage, *.d.ts
 *     - Без паттернов из `additionalIgnore` (если переданы)
 *
 * ════════════════════════════════════════════════════════════
 * ПРИМЕРЫ
 * ════════════════════════════════════════════════════════════
 *
 *   // Один файл
 *   await collectFilesForAnalysis(['./src/index.ts']);
 *   // → ['/abs/path/src/index.ts']
 *
 *   // Директория (рекурсивно)
 *   await collectFilesForAnalysis(['./src'], true);
 *   // → ['/abs/path/src/a.ts', '/abs/path/src/sub/b.ts', ...]
 *
 *   // Директория (только верхний уровень)
 *   await collectFilesForAnalysis(['./src'], false);
 *   // → ['/abs/path/src/a.ts']
 *
 *   // Смешанный вариант
 *   await collectFilesForAnalysis(['./src', './tests/index.ts'], true);
 *   // → ['/abs/path/src/a.ts', ..., '/abs/path/tests/index.ts']
 *
 *   // ✅ v1.1.0: с дополнительными исключениями
 *   await collectFilesForAnalysis(
 *     ['./src'],
 *     true,
 *     ['**\/__tests__/**', '**\/fixtures/**']
 *   );
 *   // → без тестов и фикстур
 *
 * ════════════════════════════════════════════════════════════
 * ОБРАБОТКА ОШИБОК
 * ════════════════════════════════════════════════════════════
 *
 *   - Несуществующий путь → console.warn + пропуск.
 *   - Файл без поддерживаемого расширения → пропуск.
 *   - Ошибка чтения директории внутри glob →
 *     обрабатывается самим glob (пропускается).
 *
 *   Функция НЕ выбрасывает исключения — всегда возвращает
 *   массив (возможно, пустой).
 *
 * ════════════════════════════════════════════════════════════
 * ПАРАМЕТРЫ
 * ════════════════════════════════════════════════════════════
 *
 * @param paths             — список путей (файлы и/или директории)
 * @param recursive         — искать ли рекурсивно в директориях
 *                            (по умолчанию: true)
 * @param additionalIgnore  — ✅ v1.1.0: дополнительные glob-паттерны
 *                            исключения. Мержатся с DEFAULT_IGNORE.
 *                            Дубликаты удаляются.
 *
 * @returns Promise<string[]> — массив абсолютных путей к файлам
 */
export async function collectFilesForAnalysis(
  paths: string[],
  recursive = true,
  additionalIgnore: string[] = []
): Promise<string[]> {
  const files: string[] = [];

  // ✅ v1.1.0: объединяем базовые и дополнительные паттерны,
  // убираем дубликаты через Set.
  const ignorePatterns: string[] = [
    ...new Set<string>([...DEFAULT_IGNORE, ...additionalIgnore]),
  ];

  for (const inputPath of paths) {
    // ─────────────────────────────────────────────
    // 1. Проверка существования пути
    // ─────────────────────────────────────────────
    if (!fs.existsSync(inputPath)) {
      console.warn(`⚠️ Path does not exist: ${inputPath}`);
      continue;
    }

    // ─────────────────────────────────────────────
    // 2. Определяем тип: файл или директория
    // ─────────────────────────────────────────────
    let stat: fs.Stats;
    try {
      stat = fs.statSync(inputPath);
    } catch (error) {
      // На случай race condition: файл удалён между existsSync и statSync
      console.warn(
        `⚠️ Cannot stat path: ${inputPath} (${
          error instanceof Error ? error.message : String(error)
        })`
      );
      continue;
    }

    // ─────────────────────────────────────────────
    // 3. Если это файл
    // ─────────────────────────────────────────────
    if (stat.isFile()) {
      const ext = path.extname(inputPath);
      if (DEFAULT_EXTENSIONS.includes(ext)) {
        files.push(path.resolve(inputPath));
      }
    }

      // ─────────────────────────────────────────────
      // 4. Если это директория
    // ─────────────────────────────────────────────
    else if (stat.isDirectory()) {
      const pattern = recursive
        ? `${inputPath}/**/*{${DEFAULT_EXTENSIONS.join(',')}}`
        : `${inputPath}/*{${DEFAULT_EXTENSIONS.join(',')}}`;

      try {
        const matched = await glob(pattern, {
          nodir: true,
          ignore: ignorePatterns, // ✅ v1.1.0: мержим базовые + доп.
        });

        files.push(...matched.map(f => path.resolve(f)));
      } catch (error) {
        console.warn(
          `⚠️ Cannot scan directory: ${inputPath} (${
            error instanceof Error ? error.message : String(error)
          })`
        );
        continue;
      }
    }

    // ─────────────────────────────────────────────
    // 5. Если это не файл и не директория
    //    (например, симлинк, сокет, FIFO) — пропускаем
    // ─────────────────────────────────────────────
  }

  // ─────────────────────────────────────────────
  // 6. Убираем дубликаты
  // ─────────────────────────────────────────────
  return [...new Set(files)];
}

// ============================================
// ЭКСПОРТ ПО УМОЛЧАНИЮ
// ============================================

export default collectFilesForAnalysis;
